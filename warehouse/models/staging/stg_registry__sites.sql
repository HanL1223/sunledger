select
    site_id,
    owner_display_name,
    suburb,
    cast(postcode as varchar) as postcode,
    state,
    latitude,
    timezone,
    installer_id,
    brand,
    battery_model,
    battery_units,
    battery_usable_kwh,
    warranty_years,
    warranty_eol_soh,
    rte_spec,
    pv_kwp,
    inverter_kw,
    round(pv_kwp / inverter_kw, 2) as dc_ac_ratio,
    cast(install_date as date) as install_date,
    cast(connected_on as date) as connected_on,
    source,
    certificate_recipient
from {{ source('raw', 'sites') }}
